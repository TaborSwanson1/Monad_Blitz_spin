#!/usr/bin/env node
// Translation layer: backend build + deployment -> what the frontend needs.
//
//   npm run export                 export every network in deployments/
//   npm run export -- 31337        just one chain ID
//
// Reads  out/**.json (forge build) and deployments/<chainId>.json (Deploy.s.sol),
// then asks the deployed contracts for their live config so the output is truthful.
// Writes backend/exports/:
//   abis.ts                        typed ABIs (`as const`) for viem, generated from Foundry output
//   <network>/frontend.env         paste into frontend/.env: chain mode pointed at this deployment
//   <network>/deployment.json      addresses + round timing + game list as deployed
//
// Never writes into frontend/. That folder belongs to the frontend owners.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createPublicClient, http, formatEther } from 'viem'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'out')
const DEPLOYMENTS = join(ROOT, 'deployments')
const EXPORTS = join(ROOT, 'exports')

export const NETWORKS = {
  31337: { name: 'local', label: 'Local anvil', rpc: 'http://127.0.0.1:8545' },
  10143: {
    name: 'monad-testnet',
    label: 'Monad testnet',
    rpc: process.env.MONAD_TESTNET_RPC || 'https://testnet-rpc.monad.xyz',
    explorer: 'https://testnet.monadvision.com',
  },
}

// Contracts the frontend may talk to. [export name, Foundry artifact path]
const ARTIFACTS = [
  ['blockCasinoAbi', 'BlockCasino.sol/BlockCasino.json'],
  ['chipTokenAbi', 'ChipToken.sol/ChipToken.json'],
  ['randomnessSourceAbi', 'IRandomness.sol/IRandomnessSource.json'],
  ['gameAbi', 'IGame.sol/IGame.json'],
  ['uniformGameAbi', 'UniformGame.sol/UniformGame.json'],
  ['mockRandomnessAbi', 'MockRandomness.sol/MockRandomness.json'],
  ['pythEntropyAdapterAbi', 'PythEntropyAdapter.sol/PythEntropyAdapter.json'],
]

export function loadAbis() {
  if (!existsSync(OUT)) throw new Error('No out/ folder. Run `forge build` first.')
  const abis = {}
  for (const [name, path] of ARTIFACTS) {
    const file = join(OUT, path)
    if (!existsSync(file)) throw new Error(`Missing ${path}. Run \`forge build\`.`)
    abis[name] = JSON.parse(readFileSync(file, 'utf8')).abi
  }
  return abis
}

function writeAbisTs(abis) {
  const body = Object.entries(abis)
    .map(([name, abi]) => `export const ${name} = ${JSON.stringify(abi, null, 2)} as const\n`)
    .join('\n')
  const header =
    '// GENERATED by backend/scripts/export.mjs from Foundry output. Do not edit by hand.\n' +
    '// Regenerate with: cd backend && npm run export\n\n'
  writeFileSync(join(EXPORTS, 'abis.ts'), header + body)
}

async function readLiveConfig(net, dep, abis) {
  const client = createPublicClient({ transport: http(net.rpc) })
  const casino = { address: dep.blockCasino, abi: abis.blockCasinoAbi }
  const read = (functionName, args = []) => client.readContract({ ...casino, functionName, args })

  const [genesisBlock, roundLength, bettingWindow, settleTimeout, minBet, maxBet, gameCount] = await Promise.all(
    ['genesisBlock', 'roundLength', 'bettingWindow', 'settleTimeout', 'minBet', 'maxBet', 'gameCount'].map((f) => read(f)),
  )
  const fee = await client.readContract({ address: dep.randomness, abi: abis.randomnessSourceAbi, functionName: 'fee' })

  const games = []
  for (let id = 0; id < Number(gameCount); id++) {
    const address = await read('games', [BigInt(id)])
    const g = { address, abi: abis.uniformGameAbi }
    const [name, numOutcomes, payoutBps] = await Promise.all(
      ['name', 'numOutcomes', 'payoutBps'].map((functionName) => client.readContract({ ...g, functionName })),
    )
    // `range` exists on UniformGame only. Other game types may not have it.
    const range = await client.readContract({ ...g, functionName: 'range' }).catch(() => null)
    games.push({
      id,
      name,
      address,
      numOutcomes: Number(numOutcomes),
      range: range === null ? null : Number(range),
      payoutBps: Number(payoutBps),
      multiplier: Number(payoutBps) / 10_000,
      houseEdgePct: +(100 - (Number(payoutBps) / Number(numOutcomes)) / 100).toFixed(4),
    })
  }

  return {
    genesisBlock: genesisBlock.toString(),
    roundLength: Number(roundLength),
    bettingWindow: Number(bettingWindow),
    settleTimeout: Number(settleTimeout),
    minBet: formatEther(minBet),
    maxBet: formatEther(maxBet),
    vrfFeeMon: formatEther(fee),
    games,
  }
}

function frontendEnv(net, dep) {
  return [
    `# GENERATED by backend/scripts/export.mjs. Copy into frontend/.env to point the UI at:`,
    `# ${net.label}, chain ${dep.chainId}, randomness: ${dep.randomnessKind}`,
    `VITE_MODE=chain`,
    `VITE_CHAIN_ID=${dep.chainId}`,
    `VITE_RPC_HTTP=${net.rpc}`,
    `VITE_RPC_WS=`,
    `VITE_CASINO_ADDRESS=${dep.blockCasino}`,
    `VITE_CHIP_ADDRESS=${dep.chipToken}`,
    '',
  ].join('\n')
}

export async function exportAll(onlyChainId) {
  mkdirSync(EXPORTS, { recursive: true })
  const abis = loadAbis()
  writeAbisTs(abis)
  console.log('✓ exports/abis.ts')

  const files = existsSync(DEPLOYMENTS) ? readdirSync(DEPLOYMENTS).filter((f) => f.endsWith('.json')) : []
  const ids = files.map((f) => Number(f.replace('.json', ''))).filter((id) => !onlyChainId || id === onlyChainId)
  if (ids.length === 0) console.log('  (no deployments yet: run `npm run dev` or `npm run deploy:testnet`)')

  for (const chainId of ids) {
    const net = NETWORKS[chainId]
    if (!net) {
      console.log(`  skipping unknown chain ${chainId}`)
      continue
    }
    const dep = JSON.parse(readFileSync(join(DEPLOYMENTS, `${chainId}.json`), 'utf8'))
    let config
    try {
      config = await readLiveConfig(net, dep, abis)
    } catch (e) {
      console.log(`  ✗ ${net.label}: could not read contracts at ${net.rpc} (${e.shortMessage || e.message})`)
      continue
    }
    const dir = join(EXPORTS, net.name)
    mkdirSync(dir, { recursive: true })
    const deployment = {
      network: net.name,
      chainId,
      rpc: net.rpc,
      explorer: net.explorer ?? null,
      randomnessKind: dep.randomnessKind,
      contracts: {
        blockCasino: dep.blockCasino,
        chipToken: dep.chipToken,
        randomness: dep.randomness,
        pythEntropy: dep.randomnessKind === 'pyth-entropy' ? dep.pythEntropy : null,
      },
      ...config,
      exportedAt: new Date().toISOString(),
    }
    writeFileSync(join(dir, 'deployment.json'), JSON.stringify(deployment, null, 2) + '\n')
    writeFileSync(join(dir, 'frontend.env'), frontendEnv(net, dep))
    console.log(`✓ exports/${net.name}/  (casino ${dep.blockCasino}, ${config.games.length} games, ${config.roundLength}/${config.bettingWindow} blocks)`)
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const only = process.argv[2] ? Number(process.argv[2]) : undefined
  exportAll(only).catch((e) => {
    console.error(e.message)
    process.exit(1)
  })
}
