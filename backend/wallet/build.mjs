#!/usr/bin/env node
// Builds the wallet SDK into wallet/dist/ (committed, so frontends need no backend build).
//   cd backend && npm run wallet:build
// dist/index.js: one ES module, viem left external. dist/types/: TypeScript declarations.
import { build } from 'esbuild'
import { execSync } from 'node:child_process'
import { rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
rmSync(join(HERE, 'dist'), { recursive: true, force: true })
await build({
  entryPoints: [join(HERE, 'src', 'index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: ['viem'],
  outfile: join(HERE, 'dist', 'index.js'),
  banner: { js: '// GENERATED by backend/wallet/build.mjs from backend/wallet/src. Do not edit. Docs: backend/wallet/README.md' },
  logLevel: 'error',
})
execSync('npx tsc -p tsconfig.json', { cwd: HERE, stdio: 'inherit' })
console.log('✓ wallet/dist')
