// Fair payout table for Beauty Contest vs the sim bots (Zander). Run: node sandbox/beauty-odds.mjs > frontend/src/lib/beautyOdds.ts
//
// For each guess g (0..100) it estimates S[g] = E[ 1{g wins} / (number of tied winners) ] over the bot
// crowd (same bot model as frontend/src/lib/beauty.ts: 4-9 bots, the same four reasoning levels), then sets
//   multiplier[g] = 0.98 / S[g]   (capped at 200x)
// so that paying `entry * multiplier / ties` on a win returns 98% for EVERY guess. No guess is a sweet spot.
// The bot model below must match botGuesses() in beauty.ts: if you change one, rerun this and commit both.

const ROUNDS = Number(process.env.ROUNDS ?? 4_000_000)
const CAP_X = 200
let a = 0x9e3779b9
const U = () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296 }

function bots() {
  const n = 4 + Math.floor(U() * 6)
  const out = []
  for (let b = 0; b < n; b++) {
    const kind = U()
    const bell = (U() + U() + U()) / 3 - 0.5
    let g
    if (kind < 0.2) g = U() * 100
    else if (kind < 0.55) g = 33 + bell * 24
    else if (kind < 0.85) g = 22 + bell * 18
    else g = 8 + bell * 20
    out.push(Math.min(100, Math.max(0, Math.round(g))))
  }
  return out
}

const S = new Float64Array(101)
for (let i = 0; i < ROUNDS; i++) {
  const b = bots()
  const n = b.length + 1
  let sum = 0
  for (const x of b) sum += x
  // For guess g the distances are |3n*x - 2*(sum+g)| over x in {g, bots}. Find the best bot distance once per g.
  for (let g = 0; g <= 100; g++) {
    const s = sum + g
    const dg = Math.abs(3 * n * g - 2 * s)
    let best = Infinity, ties = 1
    for (const x of b) {
      const d = Math.abs(3 * n * x - 2 * s)
      if (d < best) { best = d; ties = 1 } else if (d === best) ties++
    }
    if (dg < best) S[g] += 1
    else if (dg === best) S[g] += 1 / (ties + 1)
  }
}
const bps = []
for (let g = 0; g <= 100; g++) {
  const s = S[g] / ROUNDS
  const x = s > 0 ? Math.min(CAP_X, 0.98 / s) : CAP_X
  bps.push(Math.round(x * 10_000))
}
console.log(`// Generated by sandbox/beauty-odds.mjs (${ROUNDS.toLocaleString()} simulated rounds). Do not edit by hand.
// Payout multiplier (in basis points of the entry) for each guess 0..100: 98% divided by the guess's win share
// against the sim bot crowd, capped at ${CAP_X}x. Paying entry * BPS / 10000 / ties on a win returns about 98% at every
// guess that isn't capped. See lib/beauty.ts.
export const BEAUTY_PAYOUT_BPS: readonly number[] = [`)
for (let i = 0; i < 101; i += 10) console.log('  ' + bps.slice(i, i + 10).join(', ') + ',')
console.log(']')
console.error('win share, selected guesses:', [0, 5, 10, 15, 18, 22, 30, 40, 50, 60, 67].map((g) => `${g}:${(S[g] / ROUNDS).toFixed(4)}`).join(' '))
